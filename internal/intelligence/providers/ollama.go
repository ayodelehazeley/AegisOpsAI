// Package providers implements concrete LLM integrations for AegisOpsAI.
package providers

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"net/http"
	"time"

	"github.com/AegisOpsAI/aegisops/internal/intelligence"
	"github.com/AegisOpsAI/aegisops/internal/models"
	"github.com/AegisOpsAI/aegisops/internal/rca"
)

// OllamaConfig configures connection to a local Ollama daemon.
type OllamaConfig struct {
	BaseURL string        `json:"baseUrl"`
	Model   string        `json:"model"`
	Timeout time.Duration `json:"timeout"`
}

// OllamaProvider implements intelligence.LLMProvider using Ollama.
type OllamaProvider struct {
	cfg    OllamaConfig
	client *http.Client
}

// NewOllamaProvider creates an Ollama LLM provider.
func NewOllamaProvider(cfg OllamaConfig) *OllamaProvider {
	if cfg.BaseURL == "" {
		cfg.BaseURL = "http://localhost:11434"
	}
	if cfg.Model == "" {
		cfg.Model = "llama3"
	}
	if cfg.Timeout == 0 {
		cfg.Timeout = 60 * time.Second
	}
	return &OllamaProvider{
		cfg: cfg,
		client: &http.Client{
			Timeout: cfg.Timeout,
		},
	}
}

func (p *OllamaProvider) Name() string { return "Ollama (" + p.cfg.Model + ")" }

type ollamaGenerateRequest struct {
	Model  string `json:"model"`
	Prompt string `json:"prompt"`
	Stream bool   `json:"stream"`
}

type ollamaGenerateResponse struct {
	Response string `json:"response"`
}

func (p *OllamaProvider) GenerateIncidentSummary(ctx context.Context, prompt string) (*intelligence.IncidentSummary, error) {
	reqBody := ollamaGenerateRequest{
		Model:  p.cfg.Model,
		Prompt: "You are an SRE incident intelligence assistant. Analyze this incident and provide a concise summary with key findings:\n\n" + prompt,
		Stream: false,
	}
	b, err := json.Marshal(reqBody)
	if err != nil {
		return nil, err
	}

	req, err := http.NewRequestWithContext(ctx, http.MethodPost, p.cfg.BaseURL+"/api/generate", bytes.NewReader(b))
	if err != nil {
		return nil, err
	}
	req.Header.Set("Content-Type", "application/json")

	resp, err := p.client.Do(req)
	if err != nil {
		return nil, fmt.Errorf("ollama request failed: %w", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("ollama returned status %d", resp.StatusCode)
	}

	var res ollamaGenerateResponse
	if err := json.NewDecoder(resp.Body).Decode(&res); err != nil {
		return nil, err
	}

	return &intelligence.IncidentSummary{
		Summary:            res.Response,
		KeyFindings:        []string{"Generated by local Ollama model"},
		RecommendedActions: []string{"Review AI suggestions before executing remediation"},
	}, nil
}

func (p *OllamaProvider) ExplainRootCause(ctx context.Context, incident *models.Incident, rcaResult *rca.Result) (string, error) {
	prompt := fmt.Sprintf("Explain why incident '%s' occurred based on evidence: %+v", incident.Title, rcaResult)
	sum, err := p.GenerateIncidentSummary(ctx, prompt)
	if err != nil {
		return "", err
	}
	return sum.Summary, nil
}

func (p *OllamaProvider) SuggestRemediation(ctx context.Context, incident *models.Incident, rcaResult *rca.Result) ([]string, error) {
	return []string{
		"Investigate resource saturation and consider rolling restart",
		"Verify configuration drift against last known healthy deployment",
	}, nil
}
