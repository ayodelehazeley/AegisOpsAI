package providers

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"net/http"
	"time"

	"github.com/AegisOpsAI/aegisops/internal/intelligence"
	"github.com/AegisOpsAI/aegisops/internal/models"
	"github.com/AegisOpsAI/aegisops/internal/rca"
)

// OpenAIConfig configures OpenAI or any OpenAI-compatible endpoint (vLLM, Groq, LiteLLM, Ollama-openai).
type OpenAIConfig struct {
	BaseURL string        `json:"baseUrl"`
	APIKey  string        `json:"apiKey"`
	Model   string        `json:"model"`
	Timeout time.Duration `json:"timeout"`
}

// OpenAIProvider implements intelligence.LLMProvider using OpenAI-compatible Chat Completions API.
type OpenAIProvider struct {
	cfg    OpenAIConfig
	client *http.Client
}

// NewOpenAIProvider creates an OpenAI-compatible provider.
func NewOpenAIProvider(cfg OpenAIConfig) *OpenAIProvider {
	if cfg.BaseURL == "" {
		cfg.BaseURL = "https://api.openai.com/v1"
	}
	if cfg.Model == "" {
		cfg.Model = "gpt-4o-mini"
	}
	if cfg.Timeout == 0 {
		cfg.Timeout = 60 * time.Second
	}
	return &OpenAIProvider{
		cfg: cfg,
		client: &http.Client{
			Timeout: cfg.Timeout,
		},
	}
}

func (p *OpenAIProvider) Name() string { return "OpenAI (" + p.cfg.Model + ")" }

type chatMessage struct {
	Role    string `json:"role"`
	Content string `json:"content"`
}

type chatCompletionRequest struct {
	Model       string        `json:"model"`
	Messages    []chatMessage `json:"messages"`
	Temperature float64       `json:"temperature"`
}

type chatCompletionResponse struct {
	Choices []struct {
		Message chatMessage `json:"message"`
	} `json:"choices"`
}

func (p *OpenAIProvider) GenerateIncidentSummary(ctx context.Context, prompt string) (*intelligence.IncidentSummary, error) {
	reqBody := chatCompletionRequest{
		Model: p.cfg.Model,
		Messages: []chatMessage{
			{
				Role:    "system",
				Content: "You are AegisOpsAI SRE assistant. Provide concise, factual incident intelligence.",
			},
			{
				Role:    "user",
				Content: prompt,
			},
		},
		Temperature: 0.2,
	}

	b, err := json.Marshal(reqBody)
	if err != nil {
		return nil, err
	}

	req, err := http.NewRequestWithContext(ctx, http.MethodPost, p.cfg.BaseURL+"/chat/completions", bytes.NewReader(b))
	if err != nil {
		return nil, err
	}
	req.Header.Set("Content-Type", "application/json")
	if p.cfg.APIKey != "" {
		req.Header.Set("Authorization", "Bearer "+p.cfg.APIKey)
	}

	resp, err := p.client.Do(req)
	if err != nil {
		return nil, fmt.Errorf("openai request failed: %w", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("openai api returned status %d", resp.StatusCode)
	}

	var chatResp chatCompletionResponse
	if err := json.NewDecoder(resp.Body).Decode(&chatResp); err != nil {
		return nil, err
	}

	if len(chatResp.Choices) == 0 {
		return nil, fmt.Errorf("no completion choices returned")
	}

	content := chatResp.Choices[0].Message.Content
	return &intelligence.IncidentSummary{
		Summary:            content,
		KeyFindings:        []string{"Generated by cloud LLM inference"},
		RecommendedActions: []string{"Review AI recommendations against system policies before execution"},
	}, nil
}

func (p *OpenAIProvider) ExplainRootCause(ctx context.Context, incident *models.Incident, rcaResult *rca.Result) (string, error) {
	prompt := fmt.Sprintf("Explain the root cause for incident '%s'. Evidence: %+v", incident.Title, rcaResult)
	res, err := p.GenerateIncidentSummary(ctx, prompt)
	if err != nil {
		return "", err
	}
	return res.Summary, nil
}

func (p *OpenAIProvider) SuggestRemediation(ctx context.Context, incident *models.Incident, rcaResult *rca.Result) ([]string, error) {
	return []string{
		"Clear temporary or log files to alleviate disk saturation",
		"Scale replica count to distribute load evenly",
	}, nil
}
